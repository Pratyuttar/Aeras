#!/usr/bin/env python3
"""Generates R.kt (resource ids) from the Android string/drawable resources copied from Seal."""
import os, re, sys
import xml.etree.ElementTree as ET

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
res = os.path.join(root, "src/main/resources/aeras")
out = os.path.join(root, "src/main/kotlin/com/junkfood/seal/R.kt")

tree = ET.parse(os.path.join(res, "values/strings.xml"))
strings, plurals = [], []
for el in tree.getroot():
    if el.tag == "string":
        strings.append(el.attrib["name"])
    elif el.tag == "plurals":
        plurals.append(el.attrib["name"])

drawables = sorted(os.listdir(os.path.join(res, "drawable")))
locales = sorted(d for d in os.listdir(res) if d.startswith("values-"))

KEYWORDS = {"in", "is", "as", "do", "if", "for", "val", "var", "fun", "try", "null", "true", "false",
            "this", "else", "when", "while", "break", "class", "object", "return", "super", "throw",
            "typeof", "package", "continue", "interface", "typealias"}

def ident(n):
    return f"`{n}`" if n in KEYWORDS else n

lines = ["// Generated by tools/gen_r.py from the Android resources. Do not edit by hand.",
         "package com.junkfood.seal", "",
         "object R {", "    object string {"]
for i, n in enumerate(strings):
    lines.append(f"        const val {ident(n)} = {i + 1}")
lines += ["    }", "", "    object plurals {"]
for i, n in enumerate(plurals):
    lines.append(f"        const val {ident(n)} = {100001 + i}")
lines += ["    }", "", "    object drawable {"]
for i, f in enumerate(drawables):
    lines.append(f"        const val {ident(os.path.splitext(f)[0])} = {200001 + i}")
lines += ["    }", "}", "",
          "internal object ResourceIndex {",
          "    val stringNames: Array<String> = arrayOf(\"\", " + ", ".join(f'"{n}"' for n in strings) + ")",
          "    val pluralNames: Array<String> = arrayOf(" + ", ".join(f'"{n}"' for n in plurals) + ")",
          "    val drawableFiles: Array<String> = arrayOf(" + ", ".join(f'"{f}"' for f in drawables) + ")",
          "    val localeDirs: Array<String> = arrayOf(" + ", ".join(f'"{d}"' for d in locales) + ")",
          "    const val PLURALS_BASE = 100001",
          "    const val DRAWABLE_BASE = 200001",
          "}", ""]
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print(f"{len(strings)} strings, {len(plurals)} plurals, {len(drawables)} drawables, {len(locales)} locales")
